"""Work-item assistant port; no HTTP or UI dependencies."""

from typing import Protocol


class AssistantPort(Protocol):
    def metadata(self, article_id: str) -> dict: ...
    def suggest_metadata(self, article_id: str, values: dict) -> dict: ...
    def accept_metadata(self, article_id: str, turn_id: str, values: dict) -> dict: ...
    def get(self, article_id: str) -> dict: ...
    def send(self, article_id: str, values: dict) -> dict: ...
    def accept(self, article_id: str, turn_id: str, values: dict) -> dict: ...
    def retry(self, article_id: str, turn_id: str) -> dict: ...
    def configuration(self) -> dict: ...
    def settings(self) -> dict: ...
    def save_settings(self, values: dict) -> dict: ...
    def models(self, kind: str) -> dict: ...
