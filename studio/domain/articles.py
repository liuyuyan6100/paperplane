"""Narrow persistence port for the article editing use cases."""

from typing import Protocol


class ArticleRepository(Protocol):
    def listing(self, scope: str = "active") -> list[dict]: ...
    def manage(self, article_id: str, action: str, version: int) -> dict: ...
    def storage(self, clean: bool = False) -> dict: ...
    def get(self, article_id: str) -> dict: ...
    def save(self, values: dict, article_id: str | None = None) -> dict: ...
    def profiles(self) -> list[dict]: ...
