"""Port for reviewed cover and body image preparation."""

from typing import Protocol


class IllustrationPort(Protocol):
    def listing(self, post_id: str, archived: bool) -> dict: ...
    def get(self, post_id: str, plan_id: str) -> dict: ...
    def create(self, post_id: str, values: dict) -> dict: ...
    def change(self, post_id: str, plan_id: str, action: str, values: dict) -> dict: ...
    def upload(self, values: dict) -> dict: ...
