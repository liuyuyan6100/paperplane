"""Port for the material / outline / reviewed body creation slice."""

from typing import Protocol


class CreationPort(Protocol):
    def materials(self, query: str) -> dict: ...
    def shared(self, query: str) -> dict: ...
    def material(self, values: dict) -> dict: ...
    def listing(self, post_id: str) -> dict: ...
    def get(self, post_id: str, task_id: str) -> dict: ...
    def create(self, post_id: str, values: dict) -> dict: ...
    def change(self, post_id: str, task_id: str, action: str, values: dict) -> dict: ...
