const fs=require('fs'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
const fixture=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1380,height:980}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(fixture.url+'/#illustrations/'+fixture.plan_id);
    await page.locator('#illustration-position-1').waitFor();
    let plan=await page.evaluate(id=>api('/illustrations/'+id),fixture.plan_id);
    const first=plan.placement_options.find(p=>p.label==='章节末：一、模型文件').id;
    const second=plan.placement_options.find(p=>p.label==='章节末：二、本地接口').id;
    assert.equal(await page.locator('#illustration-position-1').inputValue(),first);
    assert.equal(await page.getByText('旧计划：追加到文章末尾（可能在署名之后）',{exact:true}).count(),0);
    const choose=page.waitForEvent('filechooser');
    await page.locator('[data-action="illustration-upload-original"][data-index="1"]').click();
    await (await choose).setFiles(fixture.image);
    await page.locator('[data-illustration-candidate]').waitFor();
    plan=await page.evaluate(id=>api('/illustrations/'+id),fixture.plan_id);
    assert.equal(plan.candidates.length,1);
    assert.equal(plan.candidates[0].origin,'original');
    assert.equal(await page.locator('[data-action="illustration-revise"]').count(),0);
    assert.equal((await page.evaluate(id=>api('/state').then(s=>s.posts.find(p=>p.id===id)),fixture.post_id)).version,1);
    await page.locator('[data-action="illustration-adopt"]').click();
    await page.waitForFunction(()=>document.querySelector('#illustration-confirm-adopt')?.disabled===false);
    await page.locator('#illustration-adopt-position').selectOption(second);
    await page.locator('#illustration-adopt-caption').fill('用户填写的原图说明');
    assert(await page.locator('#illustration-confirm-adopt').isDisabled());
    await page.locator('#illustration-preview-update').click();
    await page.waitForFunction(()=>document.querySelector('#illustration-confirm-adopt')?.disabled===false);
    assert((await page.locator('#illustration-adopt-preview').textContent()).includes('章节末：二、本地接口'));
    await page.locator('#illustration-confirm-adopt').click();
    await page.locator('[data-action="illustration-adopt"]').waitFor();
    let post=await page.evaluate(id=>api('/state').then(s=>s.posts.find(p=>p.id===id)),fixture.post_id);
    const url=plan.candidates[0].image_url;
    assert.equal(post.version,2);
    assert(post.body.indexOf(url)>post.body.indexOf('## 二、本地接口'));
    assert(post.body.indexOf(url)<post.body.indexOf('## 写在最后'));
    await page.locator('[data-action="illustration-adopt"]').click();
    await page.waitForFunction(()=>document.querySelector('#illustration-confirm-adopt')?.disabled===false);
    await page.locator('#illustration-adopt-position').selectOption(first);
    await page.locator('#illustration-preview-update').click();
    await page.waitForFunction(()=>document.querySelector('#illustration-confirm-adopt')?.disabled===false);
    await page.locator('#illustration-confirm-adopt').click();
    await page.waitForFunction(()=>!document.querySelector('#modal')?.open);
    post=await page.evaluate(id=>api('/state').then(s=>s.posts.find(p=>p.id===id)),fixture.post_id);
    assert.equal(post.version,3);
    assert(post.body.indexOf(url)<post.body.indexOf('## 二、本地接口'));
    assert.equal(post.body.split(url).length-1,1);
    assert(post.body.indexOf(url)<post.body.indexOf('——Aiclaw'));
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    assert.deepEqual(errors,[]);
    console.log('12 browser checks passed: default anchor, legacy notice, upload, no AI revise, no premature article write, preview, dirty preview guard, positional adoption, editable caption, reposition, no duplication, no JS errors/mobile overflow');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
