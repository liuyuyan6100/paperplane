const {chromium}=require('playwright');
const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
(async()=>{
 const f=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));fs.mkdirSync(f.output,{recursive:true});
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 const metadata=page.getByRole('region',{name:'AI 补齐文章信息',exact:true});
 const body=page.getByLabel('文章正文',{exact:true});
 const fill=metadata.getByRole('button',{name:'确认填入空白处',exact:true});
 const save=page.getByRole('button',{name:'保存文章',exact:true});
 try{
  await page.goto(f.url+'/editor/');
  await page.getByRole('button').filter({hasText:'信息补齐测试'}).click();
  await page.getByRole('button',{name:'摘要、署名与更多信息',exact:true}).click();
  await body.fill('最新未保存正文😀，用于本次摘要');
  await metadata.getByRole('button',{name:'AI 补齐空白信息',exact:true}).click();
  await fill.waitFor();
  await metadata.getByText('浏览器合成摘要，依据最新正文。',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('摘要',{exact:true}).inputValue(),'');
  assert.equal(await body.inputValue(),'最新未保存正文😀，用于本次摘要');
  // Stale editor input must disable old suggestions before they can overwrite it.
  await page.getByLabel('作者',{exact:true}).fill('手写署名');
  assert(await fill.isDisabled());
  await metadata.getByRole('button',{name:'按当前稿重新补齐',exact:true}).click();
  await metadata.locator('dd').nth(1).filter({hasText:'手写署名'}).waitFor();
  await fill.click();
  await page.getByText('文章信息已填入空白处，请核对后保存文章。',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('摘要',{exact:true}).inputValue(),'浏览器合成摘要，依据最新正文。');
  assert.equal(await page.getByLabel('作者',{exact:true}).inputValue(),'手写署名');
  assert.equal(await body.inputValue(),'最新未保存正文😀，用于本次摘要');
  assert.equal(await page.getByLabel('来源',{exact:true}).inputValue(),'');
  assert.equal(await page.getByLabel('封面地址',{exact:true}).inputValue(),'');
  await page.screenshot({path:path.join(f.output,'metadata-proposal.png'),fullPage:true});
  await save.click();await page.getByText('已保存为第 2 版',{exact:true}).waitFor();
  await page.reload();await page.getByRole('button').filter({hasText:'信息补齐测试'}).click();
  await page.getByRole('button',{name:'摘要、署名与更多信息',exact:true}).click();
  assert.equal(await page.getByLabel('摘要',{exact:true}).inputValue(),'浏览器合成摘要，依据最新正文。');
  assert.equal(await page.getByLabel('作者',{exact:true}).inputValue(),'手写署名');
  // A late accept reply cannot overwrite subsequent manual input.
  await page.getByLabel('摘要',{exact:true}).fill('');
  await page.getByLabel('标签（逗号分隔）',{exact:true}).fill('');
  await metadata.getByRole('button',{name:'按当前稿重新补齐',exact:true}).click();
  await fill.waitFor({state:'visible'});await page.waitForFunction(()=>!document.querySelector('.metadata-proposal button').disabled);
  let release;const gate=new Promise(resolve=>release=resolve);let entered;
  const arrived=new Promise(resolve=>entered=resolve);
  await page.route('**/metadata/*/accept',async route=>{const response=await route.fetch();entered();await gate;await route.fulfill({response});});
  await fill.click();await arrived;
  await page.getByLabel('摘要',{exact:true}).fill('晚到回复前的手写摘要');
  release();await page.unrouteAll({behavior:'wait'});
  await page.waitForFunction(()=>!document.querySelector('.metadata-action button').textContent.includes('正在'));
  assert.equal(await page.getByLabel('摘要',{exact:true}).inputValue(),'晚到回复前的手写摘要');
  await page.getByRole('button',{name:/本篇：/}).click();
  const center=page.getByRole('dialog',{name:'任务中心',exact:true});await center.waitFor();
  assert(await center.getByLabel('仅当前文章',{exact:true}).isChecked());
  await center.getByRole('button',{name:/^待确认/}).waitFor();
  await center.getByText('AI 有没有做完、哪里需要你确认、失败后怎么继续，都在这里查看；核对后可归档或移入回收站。',{exact:true}).waitFor();
  await center.getByRole('navigation',{name:'任务列表'}).getByRole('button').filter({hasText:'信息补齐测试'}).first().click();
  await center.getByText('文章信息补齐',{exact:true}).first().waitFor();
  await center.getByRole('button',{name:'打开所属文章',exact:true}).click();
  assert.equal(await page.getByLabel('摘要',{exact:true}).inputValue(),'晚到回复前的手写摘要');
  await page.setViewportSize({width:390,height:844});
  await metadata.scrollIntoViewIfNeeded();
  assert(await metadata.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  await page.screenshot({path:path.join(f.output,'metadata-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(f.output,'result.json'),JSON.stringify({passed:true,checks:['unsaved-snapshot','review-before-fill','profile-and-manual-byline','stale-proposal-disabled','empty-fields-only','body-cover-source-preserved','explicit-save-reload','late-accept-guard','article-task-filter','task-purpose-explained','mobile-bounds']},null,2));
 }catch(error){await page.screenshot({path:path.join(f.output,'failure-'+Date.now()+'.png'),fullPage:true});throw error;}finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
